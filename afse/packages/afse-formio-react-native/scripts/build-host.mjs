#!/usr/bin/env node
/**
 * Bundles host/main.tsx (the page shown inside the WebView) into one
 * self-contained HTML document — scripts, styles and fonts inlined — and
 * writes it to src/generated/host-html.ts. The app needs no web server,
 * assets or network access to show a form.
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const pkg = fileURLToPath(new URL('..', import.meta.url));

const result = await build({
  entryPoints: [`${pkg}host/main.tsx`],
  bundle: true,
  write: false,
  outdir: `${pkg}.host-build`,
  platform: 'browser',
  format: 'iife',
  target: ['es2020', 'safari14', 'chrome90'],
  minify: true,
  legalComments: 'none',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  loader: { '.woff': 'dataurl', '.woff2': 'dataurl', '.ttf': 'dataurl', '.eot': 'dataurl', '.svg': 'dataurl', '.png': 'dataurl', '.gif': 'dataurl' },
  logLevel: 'warning',
});

const js = result.outputFiles.find((f) => f.path.endsWith('.js'))?.text ?? '';
const css = result.outputFiles.find((f) => f.path.endsWith('.css'))?.text ?? '';
if (!js || !css) {
  throw new Error('build-host: expected one JS and one CSS output');
}

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, viewport-fit=cover">
<style>${css.replace(/<\/style/gi, '<\\/style')}</style>
</head>
<body>
<div id="root"></div>
<script>${js.replace(/<\/script/gi, '<\\/script')}</script>
</body>
</html>`;

mkdirSync(`${pkg}src/generated`, { recursive: true });
writeFileSync(
  `${pkg}src/generated/host-html.ts`,
  `// Generated by scripts/build-host.mjs. Do not edit.\nexport const HOST_HTML: string = ${JSON.stringify(html)};\n`,
);
console.log(`build-host: ${(html.length / 1024).toFixed(0)} KiB page written to src/generated/host-html.ts`);
